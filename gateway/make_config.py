#!/usr/bin/env python3
"""Writes LiteLLM's config.yaml from the model registry and config.base.yaml.

    python3 make_config.py [models.yaml] [config.base.yaml] [-o config.yaml]

config.base.yaml holds everything but model_list. The repository's
config.yaml is this script's output for the repository's models.yaml; a test
keeps the two in step. deploy.sh writes the production one from the
production registry.
"""
import argparse
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from croak_models import load_registry, model_list  # noqa: E402

HEADER = (
    "# croak-gate: LiteLLM proxy with the croak policy guardrail.\n"
    "# GENERATED by make_config.py from models.yaml and config.base.yaml; edit those.\n"
    "# Secrets come only from the environment (os.environ/...); see .env.example.\n"
)


def render(models_path: str, base_path: str) -> str:
    with open(models_path, encoding="utf-8") as f:
        models = load_registry(yaml.safe_load(f) or {})
    with open(base_path, encoding="utf-8") as f:
        base = yaml.safe_load(f) or {}
    if "model_list" in base:
        raise ValueError(f"{base_path} must not contain model_list; it comes from the registry")
    config = {"model_list": model_list(models), **base}
    return HEADER + yaml.safe_dump(config, sort_keys=False, allow_unicode=True, default_flow_style=False)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("models", nargs="?", default=os.path.join(HERE, "models.yaml"))
    parser.add_argument("base", nargs="?", default=os.path.join(HERE, "config.base.yaml"))
    parser.add_argument("-o", "--output")
    args = parser.parse_args()
    try:
        text = render(args.models, args.base)
    except (OSError, ValueError) as error:
        print(f"model registry: {error}", file=sys.stderr)
        return 1
    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
